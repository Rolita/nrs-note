/// 主区（标题栏下面、右侧栏左边那一块）现在显示什么。
///
/// 四个值都**不持久化**：重启回到上次的笔记，不回到图谱、白板或图片。图谱
/// 是一张结构图、白板是一块工作台、图片是一份附件——都不是一份要写的东西，
/// 每次启动都先给你看它们，等于每次都要多点一下才能写字。
enum MainView {
  note,

  /// 关系图谱。它占满正文区，而不是挤进侧边栏。
  graph,

  /// 白板。和笔记一样是一份文件（`.nrs`），但占的是主区。
  canvas,

  /// 图片。从文件树点开一张图时进来；所有图片共用这一页，换图只是换内容。
  image,

  /// 设置。以前是一层 `showDialog` 盖在窗口上，现在和别的页一样是编辑区里的
  /// 一页：能分屏、能被拖到别的格子、能一直开着改别的东西。
  settings,

  /// 模板库。以前是 `showTemplatePicker` 弹窗，插一次模板就得开一次；现在是
  /// 一页，可以一直摆在旁边，插完还留在原处。
  templates,

  /// 回收站。以前是 `showTrashDialog` 弹窗——恢复一篇就要关掉、再点开。
  trash,
}
